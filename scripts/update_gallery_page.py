"""Regenerate the 'every figure, by stage' index at the end of docs/gallery/index.md.

Run after adding a figure to a ``gallery_<stage>.py`` fixture and re-saving its baseline:

    python scripts/update_gallery_page.py
"""

from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PAGE = ROOT / "docs" / "gallery" / "index.md"
ASSETS = ROOT / "docs" / "gallery" / "assets"
MARKER = "<!-- stage-figures: generated by scripts/update_gallery_page.py; do not edit below -->"

# The six hand-built examples above the marker are described in full; the rest are indexed here.
DESCRIBED = {"enrichment", "embedding", "paired", "running_score", "volcano", "qc_summary"}
STAGES = {
    "annotation": "Annotation diagnostics",
    "ccc": "Cell-cell communication",
    "clustering": "Clustering",
    "coexpression": "Coexpression modules",
    "da": "Differential abundance and composition",
    "de": "Differential expression",
    "embeddings": "Embeddings",
    "enrichment": "Enrichment",
    "grn": "Gene regulatory networks",
    "metacells": "Metacells",
    "perturbation": "In-silico perturbation",
    "programs": "Module remodeling and multicellular programs",
    "state": "State scoring",
    "trajectory": "Trajectory",
}


def build_index() -> str:
    groups: dict[str, list[str]] = {}
    for path in sorted(ASSETS.glob("*.png")):
        name = path.stem
        if name in DESCRIBED:
            continue
        groups.setdefault(name.split("_", 1)[0], []).append(name)
    lines = [
        MARKER,
        "",
        "## Every figure, by stage",
        "",
        "Each image is drawn by the stage's own renderer from small synthetic data and is pinned "
        "by a pixel-exact test (`tests/visualization/test_figure_gallery.py`). Click one for the "
        "full size.",
        "",
    ]
    for prefix in sorted(groups, key=lambda key: STAGES.get(key, key)):
        lines += [f"### {STAGES.get(prefix, prefix)}", ""]
        for name in groups[prefix]:
            label = name.split("_", 1)[1].replace("_", " ")
            lines.append(
                f'<a href="assets/{name}.png"><img src="assets/{name}.png" width="260" '
                f'alt="{label}" title="{label}"></a>'
            )
        lines.append("")
    return "\n".join(lines)


def main() -> None:
    page = PAGE.read_text()
    head = page.split(MARKER)[0].rstrip() + "\n\n"
    PAGE.write_text(head + build_index())
    print(f"indexed {sum(1 for _ in ASSETS.glob('*.png')) - len(DESCRIBED)} stage figures")


if __name__ == "__main__":
    main()
